// Prepares a static-export build for GitHub Pages. Runs in CI only and the
// result is never committed. API routes, middleware and server-rendered pages
// need a Node server, so for the Pages build:
//   1. files listed in demo.config.json are moved / removed / patched
//      (e.g. dynamic [id] routes become ?id= query routes),
//   2. demo/overrides/ is copied over the project: client-side versions of the
//      server pages, plus src/demo/*, an in-browser stand-in for the API,
//   3. next.config.js is wrapped with output: "export" and the Pages basePath.
// Usage (from the Next.js project root): node demo/apply.mjs
import { cpSync, existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = existsSync(join(root, "src")) ? join(root, "src") : root;
const at = (p) => join(srcDir, p);
const config = JSON.parse(readFileSync(join(root, "demo", "demo.config.json"), "utf8"));

for (const [from, to] of Object.entries(config.move || {})) {
  mkdirSync(dirname(at(to)), { recursive: true });
  renameSync(at(from), at(to));
  console.log("moved   " + from + " -> " + to);
}
for (const p of config.remove || []) {
  rmSync(at(p), { recursive: true, force: true });
  console.log("removed " + p);
}
for (const { file, find, replace } of config.patch || []) {
  const text = readFileSync(at(file), "utf8");
  if (!text.includes(find)) throw new Error("patch target not found in " + file + ": " + find);
  writeFileSync(at(file), text.split(find).join(replace));
  console.log("patched " + file);
}

cpSync(join(root, "demo", "overrides"), root, { recursive: true });
console.log("copied  demo/overrides");

// keep demo/ sources out of the type-check; their copies under src/ are checked
const tsconfigPath = join(root, "tsconfig.json");
const tsconfig = JSON.parse(readFileSync(tsconfigPath, "utf8"));
tsconfig.exclude = [...new Set([...(tsconfig.exclude || []), "demo"])];
writeFileSync(tsconfigPath, JSON.stringify(tsconfig, null, 2));

const original = existsSync(join(root, "next.config.js")) ? "next.config.original.js" : null;
if (original) renameSync(join(root, "next.config.js"), join(root, original));
writeFileSync(
  join(root, "next.config.js"),
  [
    "// generated by demo/apply.mjs for the static GitHub Pages build",
    "const base = " + (original ? 'require("./' + original + '")' : "{}") + ";",
    'const basePath = process.env.PAGES_BASE_PATH || "";',
    "module.exports = {",
    "  ...base,",
    '  output: "export",',
    "  basePath,",
    "  trailingSlash: true,",
    "  images: { ...(base.images || {}), unoptimized: true },",
    "  eslint: { ignoreDuringBuilds: true },",
    "  env: { ...(base.env || {}), NEXT_PUBLIC_BASE_PATH: basePath },",
    "};",
    "",
  ].join("\n")
);
console.log("wrote   next.config.js (static export)");
